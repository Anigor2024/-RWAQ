import { clsx, type ClassValue } from "clsx"
import { twMerge } from "tailwind-merge"

export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs))
}

const ACCORD_WIDTH_CLASSES: Record<number, string> = {
  0: 'w-0',
  5: 'w-[5%]',
  10: 'w-[10%]',
  15: 'w-[15%]',
  20: 'w-[20%]',
  25: 'w-[25%]',
  30: 'w-[30%]',
  35: 'w-[35%]',
  40: 'w-[40%]',
  45: 'w-[45%]',
  50: 'w-[50%]',
  55: 'w-[55%]',
  60: 'w-[60%]',
  65: 'w-[65%]',
  70: 'w-[70%]',
  75: 'w-[75%]',
  80: 'w-[80%]',
  85: 'w-[85%]',
  90: 'w-[90%]',
  95: 'w-[95%]',
  100: 'w-full',
};

/**
 * Maps a 0-100 percentage intensity to a static Tailwind width class so
 * accord bars never require inline style attributes.
 */
export function getIntensityWidthClass(intensity: number): string {
  const clamped = Math.max(0, Math.min(100, intensity));
  const rounded = Math.round(clamped / 5) * 5;
  return ACCORD_WIDTH_CLASSES[rounded] ?? 'w-1/2';
}
